                if visible and scalar(visible, "always") == "no":
                    self.exclusions.append({"game_key": node.key, "reason": "Explicit is_visible = { always = no }; unavailable through the ordinary peace UI.", "evidence": self.evidence(source, node.line, "hidden_treaty")})
