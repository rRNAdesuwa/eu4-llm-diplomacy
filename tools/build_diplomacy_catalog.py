    def read(self, path: Path):
        relative = path.relative_to(self.game).as_posix()
        text = path.read_text(encoding="utf-8-sig", errors="replace")
        self.sources[relative] = {"path": relative, "sha256": sha256(path), "size_bytes": path.stat().st_size}
        return text

    def evidence(self, path, line, kind, detail=None):
        result = {"path": path, "line": line, "kind": kind}
        if detail:
            result["detail"] = detail
        return result

    def add(self, key, surface, evidence, *, name=None, category=None, action_id=None, continuous=False, scripted=False, label_only=False):
        action_id = action_id or ("subject." + key if surface == "subject_interaction" else "peace." + key if surface == "peace_term" else ALIASES.get(key, key))
        if action_id in self.actions:
            if evidence not in self.actions[action_id]["evidence"]:
                self.actions[action_id]["evidence"].append(evidence)
            return self.actions[action_id]
        contract_key = "subject." + key if surface == "subject_interaction" else key
        action = {
            "action_id": action_id,
            "name_zh": name or NAMES_ZH.get(key, "待译：" + key),
            "name_en": None,
            "category": category or ("subjects" if surface == "subject_interaction" else "peace_terms" if surface == "peace_term" else "favors" if "favor" in key else KEY_CATEGORY.get(key, "influence")),
            "surface": surface,
            "game_key": None if label_only else key,
            "game_key_kind": "unresolved_native_key" if label_only else "scripted_action" if scripted else "source_identifier",
            "parameters": schema(contract_key, surface, continuous),
            "parameter_status": "partial" if contract_key in PARTIAL or surface == "peace_term" else "specified",
            "parameter_note": PARAMETER_NOTES.get(contract_key, "Public request shape; native argument/setter binding and gameplay prerequisites are unverified."),
            "availability": "localization_only_unverified" if label_only else "source_declared_runtime_unverified",
            "evidence": [evidence],
            "execution": {
                "status": "unimplemented", "backend": None, "supported_builds": [],
                "reason": "No verified constructor, payload mapping, game-thread dispatch and outcome validation for this action on this build.",
            },
        }
        self.actions[action_id] = action
        return action

    def build(self):
        # Preserve each file as provenance: no full proprietary source is copied.
        diplo_files = sorted((self.game / "common/diplomatic_actions").glob("*.txt"))
        for path in diplo_files:
            source = path.relative_to(self.game).as_posix()
            text = self.read(path)
            in_header = False
            for number, line in enumerate(text.splitlines(), 1):
                if re.fullmatch(r"#\s*DIPLOMATIC ACTIONS\s*", line):
                    in_header = True
                elif in_header and line and not line.startswith("#"):
                    in_header = False
                elif in_header and (match := re.fullmatch(r"#\s*([a-z][a-z_]+)\s*", line)):
                    self.add(match[1], "diplomacy", self.evidence(source, number, "documented_native_action"))
                    self.counts["documented_native_action_occurrences"] += 1
            for node in parse_script(text):
                self.add(node.key, "diplomacy", self.evidence(source, node.line, "native_script_override"))
                self.counts["native_script_override_blocks"] += 1

        for path in sorted((self.game / "common/new_diplomatic_actions").glob("*.txt")):
            source = path.relative_to(self.game).as_posix()
            for node in parse_script(self.read(path)):
                if node.key == "static_actions":
                    for static in node.children:
                        self.add(static.key, "diplomacy", self.evidence(source, static.line, "static_action_registration"))
                        self.counts["static_action_registrations"] += 1
                else:
                    action = self.add(node.key, "diplomacy", self.evidence(source, node.line, "scripted_diplomatic_action"), scripted=True, category=scalar(node, "category"))
                    action["requires_acceptance"] = {"yes": True, "no": False}.get(scalar(node, "require_acceptance"))
                    action["script_fields"] = sorted({child.key for child in node.children})
                    self.counts["scripted_diplomatic_action_blocks"] += 1

        # Subject interactions are declared in the default type's marked section.
        # Resolve copy_from in source order, excluding empty forward declarations.
        subject_nodes = {}
        interaction_keys = {}
        subject_sources = {}
        for path in sorted((self.game / "common/subject_types").glob("*.txt")):
            source = path.relative_to(self.game).as_posix()
            text = self.read(path)
            lines = text.splitlines()
            for node in parse_script(text):
                if not node.children:
                    continue
                subject_nodes[node.key] = node
                subject_sources[node.key] = source
                if node.key != "default":
                    continue
                section = ""
                for number in range(node.line, min(node.end_line, len(lines)) + 1):
                    line = lines[number - 1]
                    if "# Subject Interactions" in line:
                        section = "interaction"
                    elif section and re.search(r"#\s*Modifiers:", line):
                        section = ""
                    elif section and "# (continuous)" in line:
                        section = "continuous"
                    elif section and re.search(r"#\s*\((immediate|special)\)", line):
                        section = "immediate"
                    if section and (match := re.match(r"\s*([a-z_]+)\s*=\s*(yes|no)\b", line)):
                        interaction_keys[match[1]] = section == "continuous"
                        self.add(match[1], "subject_interaction", self.evidence(source, number, "subject_interaction_property"), continuous=section == "continuous")

        resolved = {}
        def resolve_subject(key, stack=()):
            if key in resolved:
                return resolved[key]
            if key in stack or key not in subject_nodes:
                raise ValueError(f"Unknown/cyclic subject inheritance: {key}")
            values = {} if key == "default" else dict(resolve_subject("default", (*stack, key)))
            for child in subject_nodes[key].children:
                if child.key == "copy_from":
                    values.update(resolve_subject(child.value, (*stack, key)))
                elif child.value is not None:
                    values[child.key] = child.value
            resolved[key] = values
            return values
        for key in subject_nodes:
            resolve_subject(key)
        for key, continuous in interaction_keys.items():
            action = self.actions["subject." + key]
            action["interaction_mode"] = "toggle" if continuous else "immediate"
            action["subject_types_enabled_by_source"] = sorted(k for k, v in resolved.items() if k != "default" and v.get(key) == "yes")
            for subject_type, node in subject_nodes.items():
                for child in node.children:
                    if child.key == key and subject_type != "default":
                        action["evidence"].append(self.evidence(subject_sources[subject_type], child.line, "subject_type_override", subject_type + "=" + str(child.value)))
        self.counts["subject_types"] = len(subject_nodes) - 1
        self.counts["subject_interaction_properties"] = len(interaction_keys)
        self.correct_government_scope()

        # The GUI has dynamically filled lists, plus a few explicit controls.
        for relative in ["interface/countrydiplomacyview.gui", "interface/countrydiplomacyview.gfx", "interface/countrysubjectsview.gui", "interface/peaceview.gui"]:
            path = self.game / relative
