TOKEN = re.compile(r'\s+|#[^\n]*|"(?:\\.|[^"\\])*"|[{}=]|[^\s{}=#"]+')
LOC = re.compile(r'^\s*([A-Za-z0-9_.-]+):\d*\s+"(.*)"\s*(?:#.*)?$')


@dataclass
class Node:
    key: str
    line: int
    value: str | None = None
    children: list["Node"] = field(default_factory=list)
    end_line: int = 0


def parse_script(text: str) -> list[Node]:
    """Small structural scanner: comments/quoted braces do not alter block depth."""
    tokens = []
    line = 1
    cursor = 0
    for match in TOKEN.finditer(text):
        if match.start() != cursor:
            raise ValueError(f"Invalid or unterminated quoted token at line {line}")
        token = match.group()
        if not token.isspace() and not token.startswith("#"):
            tokens.append((token, line))
        line += token.count("\n")
        cursor = match.end()
    if cursor != len(text):
        raise ValueError(f"Invalid or unterminated quoted token at line {line}")
    index = 0

    def block(nested=False):
        nonlocal index
        nodes = []
        while index < len(tokens):
            key, start = tokens[index]
            index += 1
            if key == "}":
                if not nested:
                    raise ValueError(f"Unexpected closing brace at line {start}")
                return nodes, start
            if key in ("{", "="):
                raise ValueError(f"Unexpected token {key} at line {start}")
            node = Node(key.strip('"'), start, end_line=start)
            if index < len(tokens) and tokens[index][0] == "=":
                index += 1
                if index == len(tokens):
                    raise ValueError(f"Missing value at line {start}")
                value, finish = tokens[index]
                index += 1
                if value == "{":
                    node.children, node.end_line = block(True)
                elif value in ("}", "="):
                    raise ValueError(f"Unexpected value token {value} at line {finish}")
                else:
                    node.value = value.strip('"')
                    node.end_line = finish
            nodes.append(node)
        if nested:
            raise ValueError("Unclosed block")
        return nodes, line

    return block()[0]


def walk(nodes):
    for node in nodes:
        yield node
        yield from walk(node.children)


def scalar(node: Node, key: str):
    found = [child.value for child in node.children if child.key == key]
    return found[-1] if found else None


def sha256(path: Path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


