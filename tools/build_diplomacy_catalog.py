def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-root", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "bridge/diplomacy_catalog.json")
    parser.add_argument("--docs", type=Path, default=ROOT / "docs/diplomacy-coverage.md")
    parser.add_argument("--check", action="store_true")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--native-report", type=Path)
    group.add_argument("--no-native-report", action="store_true")
    subjects = parser.add_mutually_exclusive_group()
    subjects.add_argument("--subject-report", type=Path)
    subjects.add_argument("--no-subject-report", action="store_true")
    specials = parser.add_mutually_exclusive_group()
    specials.add_argument("--special-report", type=Path)
    specials.add_argument("--no-special-report", action="store_true")
    peace = parser.add_mutually_exclusive_group()
    peace.add_argument("--peace-report", type=Path, help="Reviewed native-action-fields peace component report")
    peace.add_argument("--no-peace-report", action="store_true")
    parser.add_argument("--peace-evidence-report", type=Path, help="Reviewed peace name/definition/source closure report")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--modes-report", type=Path, help="Reviewed fixed remaining-ID mode/command classification")
    modes.add_argument("--no-modes-report", action="store_true")
    extension = parser.add_mutually_exclusive_group()
    extension.add_argument("--extension-report", type=Path, help="Reviewed subsidy parameter-unit evidence")
    extension.add_argument("--no-extension-report", action="store_true")
    args = parser.parse_args()
    if args.game_root is None:
        sys.path.insert(0, str(ROOT / "work"))
        from local_config import get_value
        args.game_root = Path(get_value("EU4_GAME_ROOT"))
    native_report = None if args.no_native_report else args.native_report or (DEFAULT_NATIVE_REPORT if DEFAULT_NATIVE_REPORT.is_file() else None)
    subject_report = None if args.no_subject_report else args.subject_report or (DEFAULT_SUBJECT_REPORT if DEFAULT_SUBJECT_REPORT.is_file() else None)
    special_report = None if args.no_special_report else args.special_report or (DEFAULT_SPECIAL_REPORT if DEFAULT_SPECIAL_REPORT.is_file() else None)
    if args.no_peace_report and args.peace_evidence_report:
        parser.error("--peace-evidence-report conflicts with --no-peace-report")
    peace_report = None if args.no_peace_report else args.peace_report or (DEFAULT_PEACE_REPORT if DEFAULT_PEACE_REPORT.is_file() else None)
    peace_evidence = None if args.no_peace_report else args.peace_evidence_report or (DEFAULT_PEACE_EVIDENCE_REPORT if DEFAULT_PEACE_EVIDENCE_REPORT.is_file() else None)
    modes_report = None if args.no_modes_report else args.modes_report or (DEFAULT_MODES_REPORT if DEFAULT_MODES_REPORT.is_file() else None)
    extension_report = None if args.no_extension_report else args.extension_report or (DEFAULT_EXTENSION_REPORT if DEFAULT_EXTENSION_REPORT.is_file() else None)
    catalog = Builder(args.game_root.resolve(), native_report, subject_report, special_report, peace_report, peace_evidence, modes_report, extension_report).build()
    products = {args.output: json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", args.docs: render_docs(catalog)}
    stale = []
    for path, content in products.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    print(json.dumps({"mode": "check" if args.check else "write", "counts": catalog["coverage"]["counts"], "by_surface": catalog["coverage"]["by_surface"], "stale": stale}, ensure_ascii=False))
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
