                # a comment. Its bounds are UI evidence, not an engine setter.
                for dialog in walk(parse_script(text)):
                    if scalar(dialog, "name") != "TransferTradePowerDialog":
                        continue
                    for control in dialog.children:
                        if scalar(control, "name") == "trade_power_slider":
                            detail = "TransferTradePowerDialog.trade_power_slider: " + ", ".join(f"{key}={scalar(control, key)}" for key in ("minValue", "maxValue", "stepSize"))
